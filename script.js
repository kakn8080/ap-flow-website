/* ELEMENTS */
const switchButton = document.getElementById("languageSwitch");
const languageLabel = document.getElementById("languageLabel");
const mobileButton = document.getElementById("mobileMenuButton");
const nav = document.getElementById("mainNav");

/* LANGUAGE SWITCH */
function setLanguage(lang) {
  const dictionary = translations[lang] || translations.en;

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.body.classList.toggle("arabic", lang === "ar");

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");

    if (dictionary[key] !== undefined) {
      element.innerHTML = dictionary[key];
    }
  });

  if (languageLabel) {
    languageLabel.textContent = lang === "ar" ? "English" : "العربية";
  }

  if (switchButton) {
    switchButton.setAttribute(
      "aria-label",
      lang === "ar" ? "Switch to English" : "التبديل إلى العربية"
    );
  }

  localStorage.setItem("apflow-language", lang);
}

/* LANGUAGE BUTTON */
if (switchButton) {
  switchButton.addEventListener("click", () => {
    const next = document.documentElement.lang === "en" ? "ar" : "en";
    setLanguage(next);
  });
}

/* MOBILE MENU */
if (mobileButton && nav) {
  mobileButton.addEventListener("click", () => {
    const open = nav.classList.toggle("open");
    mobileButton.setAttribute("aria-expanded", String(open));
  });

  nav.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      nav.classList.remove("open");
      mobileButton.setAttribute("aria-expanded", "false");
    });
  });
}

/* FOOTER YEAR */
const yearElement = document.getElementById("year");

if (yearElement) {
  yearElement.textContent = new Date().getFullYear();
}

/* INITIAL LANGUAGE */
setLanguage(localStorage.getItem("apflow-language") || "en");
